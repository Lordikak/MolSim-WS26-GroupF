#include "outputWriter/XYZWriter.h"

#include <iomanip>
#include <sstream>

#include "ParticleContainer.h"

namespace outputWriter {

XYZWriter::XYZWriter() = default;

XYZWriter::~XYZWriter() = default;

void XYZWriter::PlotParticles(const ParticleContainer &particles, const std::string &filename,
                              int iteration) {
    std::ofstream file;
    std::stringstream strstr;
    strstr << "output/XYZ/" << filename << "_" << std::setfill('0') << std::setw(4) << iteration
           << ".xyz";
    file.open(strstr.str().c_str());
    file << particles.size() << std::endl;
    file << "Generated by MolSim. See http://openbabel.org/wiki/XYZ_(format) for "
            "file format doku."
         << std::endl;

    for (auto p : particles) {
        Vec3 x = p.x();
        file << "Ar ";
        file.setf(std::ios_base::showpoint);

        for (auto &xi : x) {
            file << xi << " ";
        }

        file << std::endl;
    }

    file.close();
}

}  // namespace outputWriter
